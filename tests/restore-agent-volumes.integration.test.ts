import { expect, it } from "vitest";
import { execFileSync } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { restoreAgentVolumes } from "../scripts/restore-agent-volumes.mjs";

it.runIf(process.env.NIMBOT_TEST_DOCKER_IMAGE)(
  "restores real archives with ownership and preserves volumes on a repeated attempt",
  async () => {
    const backup = await mkdtemp(join(tmpdir(), "nimbot-restore-docker-"));
    const agentId = `restore-${randomUUID()}`;
    const installation = randomUUID().replaceAll("-", "");
    const names = ["workspace", "engine", "tasks"].map(
      (kind) => `nimbot-${agentId}-${kind}`,
    );
    const docker = (...args: string[]) =>
      execFileSync("docker", args, { encoding: "utf8" });
    try {
      for (const name of names) {
        docker(
          "run",
          "--rm",
          "--network",
          "none",
          "--mount",
          `type=bind,src=${backup},dst=/backup`,
          "node:22-bookworm-slim",
          "sh",
          "-ec",
          'mkdir /data; printf "saved state" > /data/state; chmod 640 /data/state; chown 1000:1000 /data /data/state; tar -czf "/backup/$1.tar.gz" -C /data .',
          "sh",
          name,
        );
      }
      restoreAgentVolumes(backup, agentId, installation);
      for (const name of names) {
        const [volume] = JSON.parse(docker("volume", "inspect", name));
        expect(volume.Labels).toMatchObject({
          "io.nimbot.agent-id": agentId,
          "io.nimbot.installation": installation,
        });
        expect(
          docker(
            "run",
            "--rm",
            "--network",
            "none",
            "--user",
            "1000:1000",
            "--mount",
            `type=volume,src=${name},dst=/data,readonly`,
            "node:22-bookworm-slim",
            "sh",
            "-ec",
            'cat /data/state; stat -c "%u:%g:%a" /data/state',
          ),
        ).toBe("saved state1000:1000:640\n");
      }
      expect(() => restoreAgentVolumes(backup, agentId, installation)).toThrow(
        "already exists",
      );
      for (const name of names)
        expect(JSON.parse(docker("volume", "inspect", name))[0].Name).toBe(
          name,
        );
    } finally {
      // Only names generated by this fixture are eligible for cleanup.
      for (const name of names) {
        try {
          docker("volume", "rm", name);
        } catch {
          /* Preserve the original test error. */
        }
      }
      await rm(backup, { recursive: true, force: true });
    }
  },
  120000,
);
